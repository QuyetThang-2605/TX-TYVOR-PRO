"""Deterministic numeric-only bold fonts derived from MIT LVGL Montserrat48.
No Oxbot font, image or trademark data is read or embedded.
"""
import hashlib,json,re,math
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
def main():
    source=ROOT/'.tools/sdk/lvgl-9.2.2/src/font/lv_font_montserrat_48.c';s=source.read_text(encoding='utf-8')
    bitmap=re.search(r'uint8_t glyph_bitmap\[\]\s*=\s*\{(.*?)\};',s,re.S).group(1)
    bitmap=re.sub(r'/\*.*?\*/','',bitmap,flags=re.S);data=bytes(int(n,0) for n in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b',bitmap))
    descriptors=re.search(r'lv_font_fmt_txt_glyph_dsc_t glyph_dsc\[\]\s*=\s*\{(.*?)\};',s,re.S).group(1)
    glyphs=[dict((k,int(v)) for k,v in re.findall(r'\.(\w+)\s*=\s*(-?\d+)',body)) for body in re.findall(r'\{([^{}]+)\}',descriptors)]
    output=['/* Generated by scripts/generate-ui-v3-timer-font.py. LVGL MIT font derivative. */','#include "timer_font.h"']
    sizes={}
    for name,xscale,yscale in [('compact',0.96,1.28),('large',1.35,1.70)]:
        raw=[];rows=['{0,0,0,0,0,0}']
        for code in range(45,59):
            g=glyphs[code-31];w,h=g['box_w'],g['box_h'];pixels=[]
            for i in range(w*h):v=data[g['bitmap_index']+i//2];pixels.append((v>>4)&15 if i%2==0 else v&15)
            ow=max(1,round(w*xscale))+2;oh=max(1,round(h*yscale))+2;out=[]
            def sample(sx,sy):
                x0=math.floor(sx);y0=math.floor(sy);dx=sx-x0;dy=sy-y0;value=0.0
                for xx,wx in [(x0,1-dx),(x0+1,dx)]:
                    for yy,wy in [(y0,1-dy),(y0+1,dy)]:
                        if 0<=xx<w and 0<=yy<h:value+=pixels[yy*w+xx]*wx*wy
                return value
            for y in range(oh):
                for x in range(ow):
                    value=0.0
                    for ay in [-0.25,0.25]:
                        for ax in [-0.25,0.25]:
                            sx=(x-1+ax)/xscale;sy=(y-1+ay)/yscale
                            value+=max(sample(sx+dx,sy+dy) for dx,dy in [(0,0),(-1.35,0),(1.35,0),(0,-1.35),(0,1.35),(-0.95,-0.95),(0.95,0.95),(-0.95,0.95),(0.95,-0.95)])
                    out.append(max(0,min(15,round(value/4))))
            index=len(raw)
            if len(out)%2:out.append(0)
            raw.extend(out[i]*16+out[i+1] for i in range(0,len(out),2))
            advance=round(g['adv_w']*xscale)+16
            rows.append('{'+','.join(map(str,[index,advance,ow,oh,round(g['ofs_x']*xscale)-1,round(g['ofs_y']*yscale)-1]))+'}')
        prefix='ui3_timer_'+name;sizes[name]=len(raw)
        output+=['static const uint8_t '+prefix+'_bitmap[]={'+','.join(hex(b) for b in raw)+'};',
                 'static const lv_font_fmt_txt_glyph_dsc_t '+prefix+'_glyphs[]={'+','.join(rows)+'};',
                 'static const lv_font_fmt_txt_cmap_t '+prefix+'_map[]={ {.range_start=45,.range_length=14,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY} };',
                 'static const lv_font_fmt_txt_dsc_t '+prefix+'_dsc={.glyph_bitmap='+prefix+'_bitmap,.glyph_dsc='+prefix+'_glyphs,.cmaps='+prefix+'_map,.cmap_num=1,.bpp=4,.bitmap_format=0};',
                 'const lv_font_t tyvor_'+prefix+'={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height='+str(math.ceil(52*yscale)+2)+',.base_line='+str(round(9*yscale))+',.dsc=&'+prefix+'_dsc};']
    folder=ROOT/'experiments/tyvor_ui_v3';(folder/'timer_font.c').write_text('\n'.join(output)+'\n')
    (folder/'timer_font.h').write_text('#ifndef TYVOR_UI3_TIMER_FONT_H\n#define TYVOR_UI3_TIMER_FONT_H\n#include "lvgl.h"\nextern const lv_font_t tyvor_ui3_timer_compact,tyvor_ui3_timer_large;\n#endif\n')
    (ROOT/'build/ui-v3/evidence/font-generation.json').write_text(json.dumps(dict(source=str(source.relative_to(ROOT)),source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),license='LVGL MIT',bitmap_bytes=sizes,generated_sha256=hashlib.sha256((folder/'timer_font.c').read_bytes()).hexdigest()),indent=2)+'\n')
    print('Generated numeric LVGL fonts:',sizes)
if __name__=='__main__':main()
